/**
 * Delete a file from storage
 * Useful for cleanup or when generation fails
 */
export async function deleteFromStorage(filePath: string): Promise<void> {
    const adminClient = createAdminClient();

    const { error } = await adminClient
        .storage
        .from("generations")
        .remove([filePath]);

    if (error) {
        console.error(`[Storage] Delete failed for ${filePath}:`, error);
        throw new Error(`Failed to delete file: ${error.message}`);
    }

    console.log(`[Storage] Deleted: ${filePath}`);
}

/**
 * Check if a file exists in storage
 */
export async function fileExistsInStorage(filePath: string): Promise<boolean> {
    const adminClient = createAdminClient();

    const { data, error } = await adminClient
        .storage
        .from("generations")
        .list(filePath.split("/").slice(0, -1).join("/"), {
            search: filePath.split("/").pop(),
        });

    if (error) {
        return false;
    }

    return data.length > 0;
}
